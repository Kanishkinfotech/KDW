import axios from 'axios';
import { getSettingsByGroup, saveSetting } from '../controllers/settings/settingsService';

export interface WhatsAppConfig {
  appId?: string;
  appSecret?: string;
  wabaId?: string;
  phoneNumberId?: string;
  businessPhoneNumber?: string;
  accessToken?: string;
  webhookVerifyToken?: string;
  apiVersion?: string;
}

export interface SendWhatsAppMessageOptions {
  to: string; // E.164 phone number e.g. +919876543210
  templateName?: string;
  languageCode?: string;
  components?: any[];
  textMessage?: string;
}

export class WhatsAppService {
  private static defaultApiVersion = 'v20.0';

  /**
   * Resolves current WhatsApp configuration from database settings or environment
   */
  public static async getConfig(): Promise<WhatsAppConfig> {
    const settings = await getSettingsByGroup('INTEGRATION', true);
    const waSettings = await getSettingsByGroup('WHATSAPP', true);

    return {
      appId: waSettings.meta_app_id || settings.meta_app_id || process.env.META_APP_ID,
      appSecret: waSettings.meta_app_secret || settings.meta_app_secret || process.env.META_APP_SECRET,
      wabaId: waSettings.waba_id || settings.waba_id || process.env.META_WABA_ID,
      phoneNumberId: waSettings.phone_number_id || settings.phone_number_id || process.env.META_PHONE_NUMBER_ID,
      businessPhoneNumber: waSettings.business_phone_number || settings.business_phone_number || process.env.META_PHONE_NUMBER,
      accessToken: waSettings.access_token || settings.meta_access_token || process.env.META_ACCESS_TOKEN,
      webhookVerifyToken: waSettings.webhook_verify_token || settings.meta_verify_token || process.env.META_WEBHOOK_VERIFY_TOKEN,
      apiVersion: waSettings.api_version || this.defaultApiVersion
    };
  }

  /**
   * Verifies WhatsApp Business API credentials with Meta Graph API
   */
  public static async testConnection(customConfig?: Partial<WhatsAppConfig>): Promise<{
    success: boolean;
    status: 'CONNECTED' | 'NOT_CONFIGURED' | 'FAILED';
    message: string;
    details?: any;
  }> {
    try {
      const baseConfig = await this.getConfig();
      const raw = (customConfig || {}) as any;

      // Resolve access token (handling masked secret from UI)
      const rawToken = raw.accessToken || raw.access_token;
      const isMaskedToken = !rawToken || rawToken === '••••••••••••••••' || rawToken.includes('••••');
      const resolvedAccessToken = isMaskedToken ? baseConfig.accessToken : rawToken;

      const rawPhoneId = raw.phoneNumberId || raw.phone_number_id || baseConfig.phoneNumberId;

      const config: WhatsAppConfig = {
        appId: raw.appId || raw.meta_app_id || baseConfig.appId,
        appSecret: raw.appSecret || raw.meta_app_secret || baseConfig.appSecret,
        wabaId: raw.wabaId || raw.waba_id || baseConfig.wabaId,
        phoneNumberId: rawPhoneId ? String(rawPhoneId).trim() : undefined,
        businessPhoneNumber: raw.businessPhoneNumber || raw.business_phone_number || baseConfig.businessPhoneNumber,
        accessToken: resolvedAccessToken,
        webhookVerifyToken: raw.webhookVerifyToken || raw.webhook_verify_token || baseConfig.webhookVerifyToken,
        apiVersion: raw.apiVersion || raw.api_version || baseConfig.apiVersion || this.defaultApiVersion
      };

      if (!config.accessToken || !config.phoneNumberId) {
        return {
          success: false,
          status: 'NOT_CONFIGURED',
          message: 'WhatsApp Business API is not configured. Meta Phone Number ID and Access Token are required.'
        };
      }

      // Explicit validation for Phone Number ID
      if (config.phoneNumberId.includes('@')) {
        return {
          success: false,
          status: 'FAILED',
          message: `Invalid Phone Number ID: "${config.phoneNumberId}". Phone Number ID must be the 15-digit numeric ID generated by Meta Cloud API (e.g. 509182736450192), not an email address.`
        };
      }

      if (!/^\d+$/.test(config.phoneNumberId)) {
        return {
          success: false,
          status: 'FAILED',
          message: `Invalid Phone Number ID: "${config.phoneNumberId}". Phone Number ID must be a numeric ID from Meta App Dashboard, not a phone number or string.`
        };
      }

      const version = config.apiVersion || this.defaultApiVersion;
      const url = `https://graph.facebook.com/${version}/${config.phoneNumberId}`;

      const response = await axios.get(url, {
        headers: {
          Authorization: `Bearer ${config.accessToken}`
        },
        params: {
          fields: 'verified_name,display_phone_number,quality_rating,code_verification_status'
        },
        timeout: 10000
      });

      const data = response.data;
      return {
        success: true,
        status: 'CONNECTED',
        message: `Successfully connected to WhatsApp Business API (${data.display_phone_number || config.phoneNumberId}). Verified Name: ${data.verified_name || 'KDW'}`,
        details: data
      };
    } catch (err: any) {
      const metaError = err.response?.data?.error?.message || err.message;
      return {
        success: false,
        status: 'FAILED',
        message: `WhatsApp Business API verification failed: ${metaError}`,
        details: err.response?.data?.error
      };
    }
  }

  /**
   * Dispatches a WhatsApp Message via Meta Cloud API
   */
  public static async sendMessage(options: SendWhatsAppMessageOptions): Promise<{
    success: boolean;
    messageId?: string;
    error?: any;
  }> {
    try {
      const config = await this.getConfig();

      if (!config.accessToken || !config.phoneNumberId) {
        throw new Error('WhatsApp integration not configured. Missing Access Token or Phone Number ID.');
      }

      if (config.phoneNumberId.includes('@') || !/^\d+$/.test(config.phoneNumberId.trim())) {
        throw new Error(`Invalid Phone Number ID: "${config.phoneNumberId}". Phone Number ID must be a numeric ID from Meta, not an email address.`);
      }

      // Format recipient phone number: ensure country code, strip special characters
      let recipientPhone = options.to.replace(/[^\d+]/g, '');
      if (recipientPhone.startsWith('0')) {
        recipientPhone = '91' + recipientPhone.substring(1);
      } else if (!recipientPhone.startsWith('+') && recipientPhone.length === 10) {
        recipientPhone = '91' + recipientPhone;
      }
      recipientPhone = recipientPhone.replace('+', '');

      const version = config.apiVersion || this.defaultApiVersion;
      const url = `https://graph.facebook.com/${version}/${config.phoneNumberId}/messages`;

      let payload: any;

      if (options.templateName) {
        payload = {
          messaging_product: 'whatsapp',
          to: recipientPhone,
          type: 'template',
          template: {
            name: options.templateName,
            language: { code: options.languageCode || 'en' },
            components: options.components || []
          }
        };
      } else {
        payload = {
          messaging_product: 'whatsapp',
          to: recipientPhone,
          type: 'text',
          text: {
            preview_url: false,
            body: options.textMessage || 'Notification from Kanishk Digital World.'
          }
        };
      }

      const res = await axios.post(url, payload, {
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${config.accessToken}`
        },
        timeout: 15000
      });

      const messageId = res.data?.messages?.[0]?.id;
      return { success: true, messageId };
    } catch (err: any) {
      const errorDetail = err.response?.data?.error?.message || err.message;
      console.error('[WhatsAppService] Send message error:', errorDetail);
      return { success: false, error: errorDetail };
    }
  }
}
